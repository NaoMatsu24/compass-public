// Explicit reset of To Do history; application settings and admissions records stay intact.
function applyStudyStartReset(candidate,date){
 if(!validDate(date))throw Error('開始日を正しく入力してください。');
 const before=t=>t.date<date||(t.autoGenerated&&t.generatedFor<date);
 candidate.tasks=candidate.tasks.filter(t=>!before(t));
 const p=candidate.planner;p.startDate=date;
 p.subjectStarts.far=date;p.subjectStarts.ielts=date;
 p.beforeStartArchive={startDate:date,tasks:[],history:{}};p.replans=[];
 for(const d of Object.keys(p.history))if(d<date)delete p.history[d];
 for(const d of Object.keys(p.dateMinutes))if(d<date)delete p.dateMinutes[d];
 return candidate;
}
function buildStudyStartReset(source,date){
 const candidate=validate(clonePlanning(source));
 const removed=candidate.tasks.filter(t=>t.date<date||(t.autoGenerated&&t.generatedFor<date));
 applyStudyStartReset(candidate,date);
 return {candidate:validate(candidate),removed};
}
