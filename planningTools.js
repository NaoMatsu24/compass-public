function migratePlanningTools(s){
 const p=s.planner;
 if(p.weeklyMinutes===undefined)p.weeklyMinutes=Array(7).fill(null);
 if(!Array.isArray(p.weeklyMinutes)||p.weeklyMinutes.length!==7||p.weeklyMinutes.some(n=>n!==null&&(!Number.isInteger(n)||n<0||n>480)))throw Error('曜日別時間が不正です');
 if(p.holidayMinutes===undefined)p.holidayMinutes=300;
 if(!Number.isInteger(p.holidayMinutes)||p.holidayMinutes<0||p.holidayMinutes>480)throw Error('祝日の学習時間が不正です');
 if(p.dateMinutes===undefined)p.dateMinutes={};
 if(!p.dateMinutes||typeof p.dateMinutes!=='object'||Array.isArray(p.dateMinutes)||Object.entries(p.dateMinutes).some(([d,n])=>!validDate(d)||!Number.isInteger(n)||n<0||n>480))throw Error('日別時間が不正です');
 if(p.replans===undefined)p.replans=[];
 if(!Array.isArray(p.replans)||p.replans.some(r=>!r||!validDate(r.date)||!validDate(r.at?.slice(0,10))||!Number.isInteger(r.limit)||r.limit<0||r.limit>480||!Array.isArray(r.removed)||r.removed.some(t=>!t||typeof t.id!=='string'||typeof t.name!=='string'||!Number.isFinite(t.minutes)||t.minutes<0)||!Array.isArray(r.addedIds)||r.addedIds.some(id=>typeof id!=='string')))throw Error('再配分履歴が不正です');
 if(s.settings.backup===undefined)s.settings.backup={enabled:true,intervalDays:7,lastExported:'',snoozedUntil:''};
 const b=s.settings.backup;
 if(!b||typeof b.enabled!=='boolean'||![3,7,14,30].includes(b.intervalDays)||![b.lastExported,b.snoozedUntil].every(d=>d===''||validDate(d)))throw Error('バックアップ設定が不正です');
 for(const t of s.tasks){if(t.autoPlanOriginal!==undefined&&typeof t.autoPlanOriginal!=='string')throw Error('自動タスクの初期値が不正です');if(t.userEdited!==undefined&&typeof t.userEdited!=='boolean')throw Error('タスク編集状態が不正です');}
 for(const t of s.tasks)if(t.studyParts!==undefined){
  if(!Array.isArray(t.studyParts)||!t.studyParts.length||t.studyParts.some(p=>!p||typeof p.name!=='string'||!Number.isFinite(p.minutes)||p.minutes<=0||!dailyPlanTypes.includes(p.planType)||(p.farStudyChapterId!==undefined&&(!s.far.some(f=>f.id===p.farStudyChapterId)||typeof p.farStudyCredit!=='boolean'))))throw Error('学習内訳が不正です');
 }
 return s;
}
function scheduledMinutes(source,date=today()){
 const day=parse(date).getDay();
 return source.planner.dateMinutes?.[date]??(JP_STUDY_HOLIDAYS.has(date)?(source.planner.holidayMinutes??300):(source.planner.weeklyMinutes?.[day]??defaultWeekdayMinutes(source,day)));
}
function weeklyTarget(source,dates=weekDates()){return dates.reduce((n,d)=>n+dailyLimit(source,d),0);}
function taskPlanSignature(t){return JSON.stringify([t.name,t.category,t.date,t.deadline||'',t.minutes,t.priority||'中',t.note||'',...(t.studyParts?[JSON.stringify(t.studyParts)]:[])]);}
function isReplaceableTask(t,date,includeLegacy=false){
 return t.autoGenerated===true&&t.generatedFor===date&&t.date===date&&!t.done&&!(t.actual>0)&&!t.userEdited&&(t.autoPlanOriginal===undefined?includeLegacy:t.autoPlanOriginal===taskPlanSignature(t));
}
function buildReplan(source,date,minutes,includeLegacy=false){
 if(!validDate(date)||!Number.isInteger(minutes)||minutes<0||minutes>480)throw Error('今日の上限は0〜480分で入力してください。');
 if(date<source.planner.startDate)throw Error('学習開始日より前には再配分できません。');
 const candidate=validate(clonePlanning(source)),removed=candidate.tasks.filter(t=>isReplaceableTask(t,date,includeLegacy)),removedIds=new Set(removed.map(t=>t.id));
 candidate.tasks=candidate.tasks.filter(t=>!removedIds.has(t.id));
 candidate.planner.dateMinutes[date]=minutes;
 // Keep deleted/completed/edited slots blocked, including slots missing from today's visible list.
 const blockedIds=new Set([...(source.planner.history[date]?.taskIds||[]).filter(id=>!removedIds.has(id)),...candidate.tasks.map(t=>t.id)]);
 const added=buildDailyPlan(candidate,date,{replan:true,blockedIds});
 candidate.tasks.push(...added);
 const old=candidate.planner.history[date];
 candidate.planner.history[date]={version:2,planType:'daily-mixed',taskIds:[...new Set([...(old?.taskIds||[]),...added.map(t=>t.id)])],farTopicIds:inferFarTopicIds(candidate,date),limit:dailyLimit(candidate,date)};
 candidate.planner.replans.push({date,at:new Date().toISOString(),removed:clonePlanning(removed),addedIds:added.map(t=>t.id),limit:dailyLimit(candidate,date)});
 return {candidate,removed,added,kept:source.tasks.filter(t=>!removedIds.has(t.id)&&(t.date===date||(t.done&&t.completedDate===date)))};
}
